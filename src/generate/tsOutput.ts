export interface CustomTypes {
  [name: string]: string;  // any, or TS type for domain's base type
}

export interface CustomTypeOrigins {
  [name: string]: { [qualifiedType: string]: string };  // "schema"."type" -> type, for each Postgres type of that name
}

const
  canaryVersion: SchemaVersionCanary['version'] = 104,
  versionCanary = (cli: string) => `
// got a type error on schemaVersionCanary below? update by running \`npx ${cli}\`
export interface schemaVersionCanary extends db.SchemaVersionCanary { version: ${canaryVersion} }
`;

const declareModule = (module: string, declarations: string) => `
declare module '${module}' {
${declarations.replace(/^(?=[ \t]*\S)/gm, '  ')}
}
`;

const customTypeHeader = `/*
** Please edit this file as needed **
It's been generated by Zapatos as a custom type definition placeholder, and won't be overwritten
*/
`;

// in 'pgcast' mode: without it, 'zapatos/schema' resolves to nothing in src/db's declarations, and every type is `any`
const zapatosSchemaShim = `\n// pgcast/db's declarations import 'zapatos/schema'` +
  declareModule('zapatos/schema', `export * from 'pgcast/schema';`);

const sourceFilesForCustomTypes = (customTypes: CustomTypes, names: string) =>
  Object.fromEntries(Object.entries(customTypes)
    .map(([name, baseType]) => [
      name,
      customTypeHeader + declareModule(`${names}/custom`,
        (baseType === 'db.JSONValue' ? `import type * as db from '${names}/db';\n` : ``) +
        `export type ${name} = ${baseType};  // replace with your custom type or interface as desired`
      )
    ]));

/**
 * Warn about each custom type name that stands for more than one Postgres type: they share one
 * placeholder, and so one type. The placeholders keep their names, which edited files depend on.
 */
const warnAboutSharedCustomTypeNames = (origins: CustomTypeOrigins, config: CompleteConfig) => {
  const warn = config.warningListener === true ? console.log : config.warningListener || (() => void 0);

  for (const name of Object.keys(origins).sort()) {
    const types = Object.keys(origins[name]).sort();
    if (types.length < 2) continue;

    const
      typeList = types.slice(0, -1).join(', ') + ' and ' + types[types.length - 1],
      namesDiffer = new Set(Object.values(origins[name])).size > 1,
      filePath = path.join(config.outDir, moduleNamesOf(config), 'custom', name + config.outExt);

    warn(`Note: custom types ${typeList} are ${types.length === 2 ? 'both' : 'all'} named ${name} in TypeScript, ` +
      `so they share one type and one placeholder file, ${filePath}. ` +
      `To type them apart, rename one of them in the database` +
      (namesDiffer ? `, or give customTypesTransform a function that keeps their names apart.` : `.`));
  }
};

/**
 * Without `typeEnumsAcrossSchemas`, note the columns it would type otherwise, once per run: their type is of
 * another schema, and its enum is looked up by name in the schema of the relation.
 */
const warnAboutEnumsAcrossSchemas = (columns: string[], config: CompleteConfig) => {
  if (columns.length === 0) return;

  const
    warn = config.warningListener === true ? console.log : config.warningListener || (() => void 0),
    sorted = [...columns].sort(),
    one = sorted.length === 1,
    list = one ? sorted[0] : sorted.slice(0, -1).join(', ') + ' and ' + sorted[sorted.length - 1];

  warn(`Note: ${list} ${one ? 'has' : 'have'} a type of another schema, which is looked up by name in the schema of ` +
    `${one ? 'its' : 'their'} relation: an enum becomes an \`any\` custom type, or the enum of the same name there. ` +
    `Set typeEnumsAcrossSchemas: true to look it up in its own schema; it will be the default in pgcast 7.0.`);
};

/**
 * Warn about each `include` entry that names no relation of its schema: it generates nothing.
 * `information_schema.tables` lists only the tables and views the connecting role has a privilege on.
 */
const warnAboutUnmatchedIncludes = (unmatched: { schema: string; name: string }[], config: CompleteConfig) => {
  const warn = config.warningListener === true ? console.log : config.warningListener || (() => void 0);

  for (const { schema, name } of unmatched) {
    warn(`Note: the include entry "${name}" of schema "${schema}" matches no relation there, so it generates nothing. ` +
      `Check its spelling and case, that the relation is in schema "${schema}", and that the database role ` +
      `has a privilege on it: include names tables, views, materialised views and foreign tables.`);
  }
};

interface NamedInTS { kind: 'schema' | 'relation' | 'enum'; name: string; label: string }
interface IdentifierGroup { as: 'namespace' | 'type'; names: NamedInTS[] }

/**
 * Warn about each TypeScript name that two schemas, relations or enums of one scope take (`odd table` and
 * `odd_table`): their declarations clash. The schemas share the top level with the relations of `unprefixedSchema`.
 */
const warnAboutSharedIdentifiers = (groups: IdentifierGroup[], config: CompleteConfig) => {
  const warn = config.warningListener === true ? console.log : config.warningListener || (() => void 0);

  for (const { as, names } of groups) {
    const byIdentifier: Record<string, NamedInTS[]> = Object.create(null);  // a table may be named `constructor`
    for (const named of names) (byIdentifier[tsIdentifier(named.name, as)] ??= []).push(named);
    for (const identifier of Object.keys(byIdentifier).sort()) {
      const
        shared = byIdentifier[identifier],
        // `relations "a" and "b"`, but `relation "a" and schema "b"`
        oneKind = shared.every(named => named.kind === shared[0].kind),
        labels = shared.map(named => oneKind ? named.label : `${named.kind} ${named.label}`).sort();
      if (labels.length < 2) continue;
      warn(`Note: ${oneKind ? `${shared[0].kind}s ` : ''}${labels.slice(0, -1).join(', ')} and ` +
        `${labels[labels.length - 1]} are ${labels.length === 2 ? 'both' : 'all'} named ${identifier} in TypeScript, ` +
        `so their declarations clash. To type them apart, rename one of them in the database.`);
    }
  }
};

function indentAll(level: number, s: string) {
  if (level === 0) return s;
  return s.replace(/^/gm, ' '.repeat(level));
}

/** The text of a query less its first and last blank lines and the margin of its template literal: it runs as is. */
const unindented = (text: string) => {
  const
    lines = text.replace(/^\s*\n|\s+$/g, '').split('\n'),
    margin = Math.min(...lines.map(line => /\S/.test(line) ? line.search(/\S/) : Infinity));
  return lines.map(line => line.slice(margin)).join('\n');
};

export const tsForConfig = async (config: CompleteConfig, debug: (s: string) => void) => {
  let querySeq = 0, ended = false;
  const
    pool = new pg.Pool(config.db),  // connects at its first query
    queryFn = async (query: pg.QueryConfig, seq = querySeq++) => {
      try {
        debug(`>>> query ${seq} >>>\n${unindented(query.text)}\n+ ${JSON.stringify(query.values)}\n`);
        const result = await pool.query(query);
        debug(`<<< result ${seq} <<<\n${JSON.stringify(result, null, 2)}\n`);
        return result;

      } catch (e) {
        // the run has thrown and ended the pool, which refuses a query still to come and never serves one still
        // queued in it (with connectionTimeoutMillis, that one rejects later): reject into the run, not exit
        if (ended) throw e;
        console.log(`*** error ${seq} ***`, e);
        process.exit(1);
      }
    };

  try {
    return await tsForQueries(config, queryFn);

  } finally {
    ended = true;
    await pool.end();  // whatever the outcome: an open connection would stop a DROP DATABASE
  }
};

const tsForQueries = async (config: CompleteConfig, queryFn: (q: pg.QueryConfig) => Promise<pg.QueryResult<any>>) => {
  const
    { schemas } = config,
    enumOrder = enumOrderOf(config),  // throws before any query
    names = moduleNamesOf(config),  // so does this
    // Object.create(null): a schema or a type may be named constructor or __proto__
    customTypes: CustomTypes = Object.create(null),
    customTypeOrigins: CustomTypeOrigins = Object.create(null),
    enumsBySchema: Record<string, Promise<EnumOrders>> = Object.create(null),
    enumOrdersFor = (schema: string) => enumsBySchema[schema] ??= enumOrdersForSchema(schema, queryFn),
    enumsForSchema = async (schema: string) => (await enumOrdersFor(schema))[enumOrder],
    columnsTypedByEnumName: string[] = [],
    schemaNames = Object.keys(schemas),
    schemaData = (await Promise.all(
      schemaNames.map(async schema => {
        const
          rules = schemas[schema],
          relations = rules.exclude === '*' ? [] :  // exclude takes precedence
            await relationsInSchema(schema, queryFn),
          tables = relations
            .filter(rel => rules.include === '*' || rules.include.indexOf(rel.name) >= 0)
            .filter(rel => rules.exclude.indexOf(rel.name) < 0),
          unmatched = rules.exclude === '*' || !Array.isArray(rules.include) ? [] :
            rules.include
              .filter(name => !relations.some(rel => rel.name === name))
              .map(name => ({ schema, name })),
          enumOrders = await enumOrdersFor(schema),
          enums = enumOrders[enumOrder],
          outOfOrder = enumOrder === 'declared' ? [] : enumsOutOfOrder(enumOrders).map(name => ({ schema, name })),
          tableDefs = await Promise.all(tables.map(async table =>
            definitionForRelationInSchema(table, schema, enums, customTypes, config, queryFn, customTypeOrigins,
              enumsForSchema, columnsTypedByEnumName))),
          schemaIsUnprefixed = schema === config.unprefixedSchema,
          none = '/* (none) */',
          schemaDef = `/* === schema: ${jsdocText(schema)} === */\n` +
            (schemaIsUnprefixed ? '' : `\nexport namespace ${tsIdentifier(schema, 'namespace')} {\n`) +
            indentAll(schemaIsUnprefixed ? 0 : 2,
              `\n/* --- enums --- */\n` +
              (enumTypesForEnumData(enums) || none) +
              `\n\n/* --- tables --- */\n` +
              (tableDefs.join('\n') || none) +
              `\n\n/* --- aggregate types --- */\n` +
              (schemaIsUnprefixed ?
                `\nexport namespace ${tsIdentifier(schema, 'namespace')} {` + (indentAll(2, crossTableTypesForTables(tables) || none)) + '\n}\n' :
                (crossTableTypesForTables(tables) || none))
            ) + '\n' +
            (schemaIsUnprefixed ? '' : `}\n`);

        const
          named = (kind: 'relation' | 'enum', name: string): NamedInTS => ({ kind, name, label: `"${schema}"."${name}"` }),
          relationNames = tables.map(rel => named('relation', rel.name)),
          // the relations of unprefixedSchema are at the top level, with the schemas' namespaces
          identifierGroups: IdentifierGroup[] = [{ as: 'type', names: Object.keys(enums).map(name => named('enum', name)) },
            ...schemaIsUnprefixed ? [] : [{ as: 'namespace' as const, names: relationNames }]],
          topLevelNames = schemaIsUnprefixed ? relationNames : [];
        return { schemaDef, tables, unmatched, outOfOrder, identifierGroups, topLevelNames };
      }))
    ),
    schemaDefs = schemaData.map(r => r.schemaDef),
    schemaTables = schemaData.map(r => r.tables),
    allTables = ([] as Relation[]).concat(...schemaTables),
    hasCustomTypes = Object.keys(customTypes).length > 0,
    ts = header() + declareModule(`${names}/schema`,
      `\nimport type * as db from '${names}/db';\n` +
      (hasCustomTypes ? `import type * as c from '${names}/custom';\n` : ``) +
      versionCanary(names) + '\n\n' +
      schemaDefs.join('\n\n') +
      `\n\n/* === global aggregate types === */\n` +
      crossSchemaTypesForSchemas(schemaNames) +
      `\n\n/* === lookups === */\n` +
      crossSchemaTypesForAllTables(allTables, config.unprefixedSchema)
    ) + (names === 'pgcast' ? zapatosSchemaShim : ''),
    customTypeSourceFiles = sourceFilesForCustomTypes(customTypes, names);

  warnAboutUnmatchedIncludes(schemaData.flatMap(r => r.unmatched), config);
  warnAboutSharedIdentifiers([...schemaData.flatMap(r => r.identifierGroups), { as: 'namespace', names: [
    ...schemaNames.map(schema => ({ kind: 'schema' as const, name: schema, label: `"${schema}"` })),
    ...schemaData.flatMap(r => r.topLevelNames)] }], config);
  warnAboutSharedCustomTypeNames(customTypeOrigins, config);
  warnAboutEnumsAcrossSchemas(columnsTypedByEnumName, config);
  warnAboutEnumOrder(schemaData.flatMap(r => r.outOfOrder), config);

  return { ts, customTypeSourceFiles };
};
