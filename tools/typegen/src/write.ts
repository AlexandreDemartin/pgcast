import { randomUUID } from 'node:crypto';
import { open, rename, rm, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { ResultField } from './values';
import { textTypes } from './values';

interface Query {
  text: string;
  fields: readonly ResultField[] | null;
}

export interface StoredQuery {
  text: string;
  fields: { name: string; type: string }[] | null;
}

export const literal = (value: string) => JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

export const header = "/*\n** DON'T EDIT THIS FILE **\nGenerated by @pgcast/typegen. Regenerating it overwrites your edits.\n*/";
export const aliases = [
  "export type Row<N extends keyof Queries> = Extract<Queries[N], { row: unknown }>['row'];",
  'export type PgArray<T> = (T | null | PgArray<T>)[];',
].join('\n');

export function typedQueries(queries: ReadonlyMap<string, Query>) {
  const typed = new Map<string, StoredQuery>();
  for (const [name, { text, fields }] of queries) {
    typed.set(name, { text, fields: fields?.map(field => {
      const value = field.enumLabels?.map(literal).join(' | ') ?? textTypes[field.dataTypeID] ?? 'string';
      return { name: field.name, type: value + (field.notNull ? '' : ' | null') };
    }) ?? null });
  }
  return typed;
}

/** The module as generation would write it, after checking every result field. */
export function buildQueries(dbModule: 'zapatos/db' | 'pgcast/db', queries: ReadonlyMap<string, StoredQuery>) {
  const lines = ['export interface Queries {'], imports = new Set<string>();
  let usesBuffer = false;
  for (const name of [...queries.keys()].sort()) {
    const { text, fields } = queries.get(name)!;
    lines.push(`  ${literal(name)}: {`, `    text: ${literal(text)};`);
    if (fields !== null) {
      const names = new Set<string>();
      lines.push('    row: {');
      for (const field of fields) {
        if (field.name === '__proto__' || names.has(field.name)) {
          const reason = field.name === '__proto__' ? 'uses reserved field' : 'repeats field';
          throw new Error(`Query ${literal(name)} ${reason} ${literal(field.name)}. Give it a distinct SQL alias.`);
        }
        names.add(field.name);
        if (!field.type.startsWith('"')) {
          if (field.type.includes('Buffer')) usesBuffer = true;
          for (const imported of ['JSONValue', 'PostgresInterval']) {
            if (field.type.includes(imported)) imports.add(imported);
          }
        }
        lines.push(`      ${literal(field.name)}: ${field.type};`);
      }
      lines.push('    };');
    }
    lines.push('  };');
  }
  lines.push('}', '', aliases, '');
  if (imports.size) lines.unshift(`import type { ${[...imports].sort().join(', ')} } from ${literal(dbModule)};`, '');
  if (usesBuffer) lines.unshift('/// <reference types="node" />', '');
  lines.unshift(header, '');
  return lines.join('\n');
}

/**
 * Write a module of named rows, replacing the destination after all fields are checked.
 * Keep the destination permissions when available, or create the file with ordinary permissions.
 * Killing the process mid-write can leave its .pgcast-* temporary file beside the destination.
 */
export async function writeQueries(path: string, dbModule: 'zapatos/db' | 'pgcast/db', queries: ReadonlyMap<string, Query>) {
  const content = buildQueries(dbModule, typedQueries(queries)), temporary = join(dirname(path), '.pgcast-' + randomUUID()),
    bits = await stat(path).then(existing => existing.mode & 0o7777, () => undefined),
    file = await open(temporary, 'wx', bits ?? 0o666);
  try {
    try {
      if (bits !== undefined) await file.chmod(bits);
      await file.writeFile(content);
    } finally {
      await file.close();
    }
    await rename(temporary, path);
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
}
