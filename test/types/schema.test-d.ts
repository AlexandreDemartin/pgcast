// Characterization of the generated row types (test/generated/zapatos/schema.d.ts),
// one family of column at a time, as a consumer sees them through 'zapatos/schema'.
// Surprises are frozen with a `characterization:` comment, not fixed.

import { describe, expectTypeOf, test } from 'vitest';
import type * as db from 'zapatos/db';
import type * as s from 'zapatos/schema';

type Where<V> = V | db.Parameter<V> | db.SQLFragment | db.ParentColumn | db.SQLFragment<any, V | db.Parameter<V> | db.SQLFragment | db.ParentColumn>;

describe('nullable column (users.manager_id)', () => {
  test('Selectable and JSONSelectable include null', () => {
    expectTypeOf<s.users.Selectable['manager_id']>().toEqualTypeOf<number | null>();
    expectTypeOf<s.users.JSONSelectable['manager_id']>().toEqualTypeOf<number | null>();
  });

  test('Insertable is optional and accepts null and DEFAULT', () => {
    expectTypeOf<s.users.Insertable['manager_id']>()
      .toEqualTypeOf<number | db.Parameter<number> | null | db.DefaultType | db.SQLFragment | undefined>();
  });

  test('Whereable leaves null out', () => {
    expectTypeOf<s.users.Whereable['manager_id']>().toEqualTypeOf<Where<number> | undefined>();
    // @ts-expect-error `= NULL` would match no row: null is not a Whereable value
    const w: s.users.Whereable = { manager_id: null };
    void w;
  });

  test('exactOptionalPropertyTypes: an explicit undefined is refused', () => {
    // @ts-expect-error undefined would compile to `= NULL` (Whereable)
    const w: s.users.Whereable = { manager_id: undefined };
    // @ts-expect-error undefined would set the column to NULL (Updatable)
    const u: s.users.Updatable = { manager_id: undefined };
    void w; void u;
  });
});

describe('NOT NULL column with a default (accounts.balance, users.created_at)', () => {
  test('optional in Insertable, without null', () => {
    expectTypeOf<s.accounts.Insertable['balance']>()
      .toEqualTypeOf<(number | db.NumericString) | db.Parameter<number | db.NumericString> | db.DefaultType | db.SQLFragment | undefined>();
    // @ts-expect-error a NOT NULL column refuses null, default or not
    const i: s.accounts.Insertable = { owner_id: 1, balance: null };
    void i;
  });

  test('a NOT NULL column without default is required', () => {
    // @ts-expect-error owner_id is NOT NULL without default
    const i: s.accounts.Insertable = {};
    void i;
  });
});

describe('generated column (products.price_with_vat_cents, products.search)', () => {
  test('selectable, nullable', () => {
    expectTypeOf<s.products.Selectable['price_with_vat_cents']>().toEqualTypeOf<db.NumericString | null>();
  });

  test('neither insertable nor updatable', () => {
    expectTypeOf<keyof s.products.Insertable & ('price_with_vat_cents' | 'search')>().toEqualTypeOf<never>();
    expectTypeOf<keyof s.products.Updatable & ('price_with_vat_cents' | 'search')>().toEqualTypeOf<never>();
  });
});

describe('identity column', () => {
  test('GENERATED ALWAYS (users.id): neither insertable nor updatable', () => {
    expectTypeOf<keyof s.users.Insertable & 'id'>().toEqualTypeOf<never>();
    expectTypeOf<keyof s.users.Updatable & 'id'>().toEqualTypeOf<never>();
    expectTypeOf<s.users.Selectable['id']>().toEqualTypeOf<number>();
  });

  test('GENERATED BY DEFAULT (accounts.id): optional in Insertable, in Updatable', () => {
    type Int8 = number | db.Int8String | bigint;
    expectTypeOf<s.accounts.Insertable['id']>()
      .toEqualTypeOf<Int8 | db.Parameter<Int8> | db.DefaultType | db.SQLFragment | undefined>();
    expectTypeOf<s.accounts.Updatable['id']>()
      .toEqualTypeOf<Int8 | db.Parameter<Int8> | db.DefaultType | db.SQLFragment
        | db.SQLFragment<any, Int8 | db.Parameter<Int8> | db.DefaultType | db.SQLFragment> | undefined>();
  });
});

describe('domain (users.email, accounts.overdraft_limit, users.tags)', () => {
  test('typed by its custom placeholder, edited to the base type in test/generated', () => {
    expectTypeOf<s.users.Selectable['email']>().toEqualTypeOf<string>();
    expectTypeOf<s.accounts.Selectable['overdraft_limit']>().toEqualTypeOf<number | null>();
    expectTypeOf<s.users.Selectable['tags']>().toEqualTypeOf<string[] | null>();
  });
});

describe('enum', () => {
  test('same schema (users.mood): the union of its labels', () => {
    expectTypeOf<s.users.Selectable['mood']>().toEqualTypeOf<'happy' | 'ok' | 'sad' | null>();
    // @ts-expect-error 'angry' is not a label of public.mood
    const i: s.users.Insertable = { email: 'a@b', display_name: 'A', mood: 'angry' };
    void i;
  });

  test('characterization: another schema (products.status, extra.status) is `any`', () => {
    // characterization: typed c.PgStatus, an `any` placeholder; any value is accepted
    expectTypeOf<s.products.Selectable['status']>().toBeAny();
    const i: s.products.Insertable = { sku: 'x', price_cents: 1, status: 'no such label' };
    void i;
  });
});

describe('array', () => {
  test('one dimension (accounts.scores)', () => {
    expectTypeOf<s.accounts.Selectable['scores']>().toEqualTypeOf<number[]>();
  });

  test('characterization: two dimensions (accounts.grid int[][]) are typed as one', () => {
    // characterization: pg returns [[1, 2], [3, 4]], typed number[]
    expectTypeOf<s.accounts.Selectable['grid']>().toEqualTypeOf<number[] | null>();
  });
});

describe('jsonb (users.settings)', () => {
  test('JSONValue in every row type', () => {
    expectTypeOf<s.users.Selectable['settings']>().toEqualTypeOf<db.JSONValue>();
    expectTypeOf<s.users.JSONSelectable['settings']>().toEqualTypeOf<db.JSONValue>();
  });
});

describe('int8 and numeric', () => {
  test('a string in Selectable, a number in JSONSelectable', () => {
    expectTypeOf<s.accounts.Selectable['lifetime_ops']>().toEqualTypeOf<db.Int8String>();
    expectTypeOf<s.accounts.JSONSelectable['lifetime_ops']>().toEqualTypeOf<number>();
    expectTypeOf<s.accounts.Selectable['balance']>().toEqualTypeOf<db.NumericString>();
    expectTypeOf<s.accounts.JSONSelectable['balance']>().toEqualTypeOf<number>();
  });

  test('int8 accepts a number, a string or a bigint on insert', () => {
    const i: s.accounts.Insertable = { owner_id: 1, lifetime_ops: BigInt(1) };
    const j: s.accounts.Insertable = { owner_id: 1, lifetime_ops: '1' };
    void i; void j;
    // @ts-expect-error 'x' is not `${number}`
    const k: s.accounts.Insertable = { owner_id: 1, lifetime_ops: 'x' };
    void k;
  });
});

describe('dates', () => {
  test('date (accounts.opened_on): Date, DateString in JSON', () => {
    expectTypeOf<s.accounts.Selectable['opened_on']>().toEqualTypeOf<Date>();
    expectTypeOf<s.accounts.JSONSelectable['opened_on']>().toEqualTypeOf<db.DateString>();
  });

  test('timestamptz (users.created_at): Date, TimestampTzString in JSON', () => {
    expectTypeOf<s.users.Selectable['created_at']>().toEqualTypeOf<Date>();
    expectTypeOf<s.users.JSONSelectable['created_at']>().toEqualTypeOf<db.TimestampTzString>();
  });
});

describe('custom type', () => {
  test('characterization: a composite (users.home) is an `any` placeholder', () => {
    expectTypeOf<s.users.Selectable['home']>().toBeAny();
  });
});

describe('views', () => {
  test('characterization: a view (active_users) has an Insertable, every column optional and nullable', () => {
    // characterization: the codegen cannot tell an updatable view; NOT NULL of users.id is lost
    expectTypeOf<s.active_users.Selectable['id']>().toEqualTypeOf<number | null>();
    expectTypeOf<s.active_users.Insertable['id']>()
      .toEqualTypeOf<number | db.Parameter<number> | null | db.DefaultType | db.SQLFragment | undefined>();
    expectTypeOf<s.active_users.Insertable['display_name']>()
      .toEqualTypeOf<string | db.Parameter<string> | null | db.DefaultType | db.SQLFragment | undefined>();
  });

  test('a materialized view (account_totals) takes no Insertable or Updatable key', () => {
    expectTypeOf<s.account_totals.Insertable>().toEqualTypeOf<{ [key: string]: never }>();
    expectTypeOf<s.account_totals.Updatable>().toEqualTypeOf<{ [key: string]: never }>();
    // @ts-expect-error a materialized view is not insertable
    const i: s.account_totals.Insertable = { owner_id: 1 };
    void i;
  });
});

describe('*ForTable<T> lookups', () => {
  test('give the namespace types, prefixed table names included', () => {
    expectTypeOf<s.SelectableForTable<'users'>>().toEqualTypeOf<s.users.Selectable>();
    expectTypeOf<s.JSONSelectableForTable<'extra.articles'>>().toEqualTypeOf<s.extra.articles.JSONSelectable>();
    expectTypeOf<s.InsertableForTable<'accounts'>>().toEqualTypeOf<s.accounts.Insertable>();
    expectTypeOf<s.UpdatableForTable<'accounts'>>().toEqualTypeOf<s.accounts.Updatable>();
    expectTypeOf<s.WhereableForTable<'users'>>().toEqualTypeOf<s.users.Whereable>();
    expectTypeOf<s.ColumnForTable<'users'>>().toEqualTypeOf<keyof s.users.Selectable>();
    expectTypeOf<s.UniqueIndexForTable<'users'>>().toEqualTypeOf<'users_email_key' | 'users_pkey'>();
    // shared_name_idx: unique on extra.articles, a plain index on public.transfers
    expectTypeOf<s.UniqueIndexForTable<'extra.articles'>>().toEqualTypeOf<'articles_pkey' | 'shared_name_idx'>();
    expectTypeOf<s.UniqueIndexForTable<'transfers'>>().toEqualTypeOf<'transfers_pkey'>();
  });

  test('refuse a table that does not exist', () => {
    // @ts-expect-error 'nope' is not a Table
    expectTypeOf<s.SelectableForTable<'nope'>>();
    // @ts-expect-error a table of schema extra needs its prefix
    expectTypeOf<s.SelectableForTable<'articles'>>();
  });
});
