describe('PostgresInterval, the type intervalsTypedAsObjects writes', () => {
  test('holds the parts of an interval, each optional, as pg leaves out a part that is zero', () => {
    const zero: db.PostgresInterval = { toPostgres: () => '0', toISO: () => 'P0Y0M0DT0H0M0S' };
    expectTypeOf(zero.days).toEqualTypeOf<number | undefined>();
    expectTypeOf(zero.milliseconds).toEqualTypeOf<number | undefined>();
    expectTypeOf(zero.toPostgres()).toEqualTypeOf<string>();
  });

  test('refuses an object without toPostgres(), through which pg writes it', () => {
    // @ts-expect-error a plain object, which pg sends as JSON: Postgres 17 and later refuse it (22007), earlier ones store one second
    const plain: db.PostgresInterval = { days: 1 };
    // @ts-expect-error toPostgres() alone missing
    const noToPostgres: db.PostgresInterval = { days: 1, toISO: () => 'P0Y0M1DT0H0M0S' };
    // @ts-expect-error toISO() too, which every postgres-interval that pg 7 and 8 use has
    const noISO: db.PostgresInterval = { days: 1, toPostgres: () => '1 day' };
    void [plain, noToPostgres, noISO];
  });
});

describe('DomainInContext, the type domainsTypedByContext writes', () => {
  test('a placeholder that holds what the generator wrote takes the type of the context', () => {
    expectTypeOf<db.DomainInContext<db.Int8String, db.Int8String, number>>().toEqualTypeOf<number>();
    expectTypeOf<db.DomainInContext<Date, Date, db.DateString | Date>>().toEqualTypeOf<db.DateString | Date>();
    // the same type, written otherwise
    expectTypeOf<db.DomainInContext<`${number}`, db.Int8String, number>>().toEqualTypeOf<number>();
    expectTypeOf<db.DomainInContext<db.Int8String[], db.Int8String[], number[]>>().toEqualTypeOf<number[]>();
  });

  test('an edited placeholder keeps its type, in every context', () => {
    type Brand = db.Int8String & { readonly __brand: 'ticket_no' };
    expectTypeOf<db.DomainInContext<number | db.Int8String, db.Int8String, number>>().toEqualTypeOf<number | db.Int8String>();
    expectTypeOf<db.DomainInContext<Brand, db.Int8String, number>>().toEqualTypeOf<Brand>();
    expectTypeOf<db.DomainInContext<string, db.Int8String, number>>().toEqualTypeOf<string>();
    expectTypeOf<db.DomainInContext<any, db.Int8String, number>>().toBeAny();
    expectTypeOf<db.DomainInContext<never, db.Int8String, number>>().toBeNever();
    // an array of any, as a placeholder Zapatos 6.6.1 wrote over int8[] with no import: not typed by context
    expectTypeOf<db.DomainInContext<any[], db.Int8String[], number[]>>().toEqualTypeOf<any[]>();
    expectTypeOf<db.DomainInContext<{ a: any }, { a: db.Int8String }, number>>().toEqualTypeOf<{ a: any }>();
  });

  test('refused', () => {
    // @ts-expect-error the context's number, not the placeholder's string
    expectTypeOf<db.DomainInContext<db.Int8String, db.Int8String, number>>().toEqualTypeOf<db.Int8String>();
    // @ts-expect-error an edited placeholder is not replaced by the context's type
    expectTypeOf<db.DomainInContext<number | db.Int8String, db.Int8String, number>>().toEqualTypeOf<number>();
    // @ts-expect-error a brand is not replaced either
    expectTypeOf<db.DomainInContext<db.Int8String & { readonly b: 1 }, db.Int8String, number>>().toEqualTypeOf<number>();
    // @ts-expect-error an array of any is not replaced either
    expectTypeOf<db.DomainInContext<any[], db.Int8String[], number[]>>().toEqualTypeOf<number[]>();
  });

  test('a domain over a domain, or an array of one: a placeholder that holds any, as generated, takes the context\'s type', () => {
    expectTypeOf<db.DomainInContext<any, any, number>>().toEqualTypeOf<number>();
    expectTypeOf<db.DomainInContext<any, any, string>>().toEqualTypeOf<string>();
    // edited, to unknown among others: its type
    expectTypeOf<db.DomainInContext<unknown, any, number>>().toBeUnknown();
    expectTypeOf<db.DomainInContext<any[], any, number[]>>().toEqualTypeOf<any[]>();
    expectTypeOf<db.DomainInContext<number | db.Int8String, any, number>>().toEqualTypeOf<number | db.Int8String>();
    // @ts-expect-error unknown is not replaced by the context's type
    expectTypeOf<db.DomainInContext<unknown, any, number>>().toEqualTypeOf<number>();
    // @ts-expect-error nor an array of any
    expectTypeOf<db.DomainInContext<any[], any, number[]>>().toEqualTypeOf<number[]>();
  });
});

describe('enum', () => {
  test('same schema (users.mood): the union of its labels', () => {
    expectTypeOf<s.users.Selectable['mood']>().toEqualTypeOf<'happy' | 'ok' | 'sad' | null>();
    // @ts-expect-error 'angry' is not a label of public.mood
    const i: s.users.Insertable = { email: 'a@b', display_name: 'A', mood: 'angry' };
    void i;
  });

  test('foreign columns take the labels of their enum', () => {
    expectTypeOf<s.products.Selectable['status']>().toEqualTypeOf<'draft' | 'published' | 'archived'>();
    db.insert('products', { sku: 'x', price_cents: 1, status: 'draft' });
    // @ts-expect-error outside extra.status
    db.insert('products', { sku: 'x', price_cents: 1, status: 'no such label' });
    // @ts-expect-error outside public.mood
    db.insert('extra.type_zoo', { c_enum_array: ['meh'] });
  });

  test('every.<enum> follows Postgres order', () => {
    expectTypeOf<s.every.mood>().toEqualTypeOf<['sad', 'ok', 'happy']>();
    expectTypeOf<s.every.mood[0]>().toEqualTypeOf<'sad'>();
  });
});

